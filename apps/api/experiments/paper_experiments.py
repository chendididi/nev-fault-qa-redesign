def main() -> None:
    parser = argparse.ArgumentParser(description="Generate paper experiment artifacts.")
    parser.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR))
    parser.add_argument("--eval-csv", default=str(API_ROOT / "retrieval_eval_hybrid_rerank_results.csv"))
    parser.add_argument("--ablation-csv", default=str(API_ROOT / "retrieval_eval_results.csv"))
    parser.add_argument(
        "--database-url",
        default=os.getenv("DATABASE_URL", "postgresql+psycopg://nev:nev_password@localhost:5432/nev_fault_qa"),
    )
    parser.add_argument("--max-chunks", type=int, default=5000)
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    figure_dir = out_dir / "figures"
    table_dir = out_dir / "tables"
    figure_dir.mkdir(parents=True, exist_ok=True)
    table_dir.mkdir(parents=True, exist_ok=True)

    configure_style()

    created: list[Path] = []
    eval_df = read_csv_if_exists(Path(args.eval_csv))
    ablation_df = read_csv_if_exists(Path(args.ablation_csv))
    chunks_df = load_chunks(args.database_url, args.max_chunks)

    if ablation_df is not None and not ablation_df.empty:
        summary = summarize_retrieval(ablation_df)
        summary_path = table_dir / "retrieval_ablation_summary.csv"
        summary.to_csv(summary_path, index=False)
        created.append(summary_path)
        created.append(plot_retrieval_ablation(summary, figure_dir))
        created.append(plot_retrieval_category_breakdown(ablation_df, figure_dir))

    if eval_df is not None and not eval_df.empty:
        metric_path = table_dir / "hybrid_rerank_case_metrics.csv"
        eval_df.to_csv(metric_path, index=False)
        created.append(metric_path)
        created.append(plot_score_pairplot(eval_df, figure_dir))
        created.append(plot_latency_dashboard(eval_df, figure_dir))

    if chunks_df is not None and not chunks_df.empty:
        chunks_path = table_dir / "knowledge_chunk_features.csv"
        chunks_df.drop(columns=["embedding"], errors="ignore").to_csv(chunks_path, index=False)
        created.append(chunks_path)
        created.append(plot_chunk_projection(chunks_df, figure_dir))
        created.append(plot_chunk_feature_pairplot(chunks_df, figure_dir))

    if eval_df is not None and not eval_df.empty and chunks_df is not None and not chunks_df.empty:
        created.append(plot_paper_dashboard(eval_df, chunks_df, figure_dir))

    manifest = {
        "out_dir": str(out_dir),
        "figures": [str(path.relative_to(out_dir)) for path in created if path.suffix.lower() in {".png", ".pdf"}],
        "tables": [str(path.relative_to(out_dir)) for path in created if path.suffix.lower() == ".csv"],
        "notes": [
            "Retrieval metrics come from the CSV files generated by apps/api/evaluate_retrieval.py.",
            "Chunk projection and feature plots are computed from the live PostgreSQL/pgvector chunks table.",
            "If you need fresh ablation numbers, rerun evaluate_retrieval.py before this script.",
        ],
    }
    manifest_path = out_dir / "experiment_manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    created.append(manifest_path)

    print("Generated paper experiment artifacts:")
    for path in created:
        print(f"- {path}")


def configure_style() -> None:
    sns.set_theme(style="whitegrid", context="paper", font_scale=1.1)
    font_paths = [
        "/mnt/c/Windows/Fonts/msyh.ttc",
        "/mnt/c/Windows/Fonts/simhei.ttf",
        "/usr/share/fonts/truetype/wqy/wqy-microhei.ttc",
    ]
    for font_path in font_paths:
        if Path(font_path).exists():
            font_manager.fontManager.addfont(font_path)
            prop = font_manager.FontProperties(fname=font_path)
            plt.rcParams["font.sans-serif"] = [prop.get_name()]
            break
    plt.rcParams["axes.unicode_minus"] = False
    plt.rcParams["figure.dpi"] = 160
    plt.rcParams["savefig.dpi"] = 300


def read_csv_if_exists(path: Path) -> pd.DataFrame | None:
    if not path.exists():
        print(f"[skip] CSV not found: {path}", file=sys.stderr)
        return None
    return pd.read_csv(path)


def summarize_retrieval(df: pd.DataFrame) -> pd.DataFrame:
    rename_map = {
        "dense": "Dense",
        "dense_only": "Dense",
        "dense_rerank": "Dense+Rerank",
        "dense_keyword": "Dense+Keyword",
        "hybrid_rerank": "Hybrid+Rerank",
        "no_rag": "No RAG",
    }
    annotated = df.copy()
    annotated["method"] = annotated["variant"].map(rename_map).fillna(annotated["variant"])
    annotated["expected_documents_n"] = annotated["expected_documents"].fillna("").apply(_csv_list_len)
    annotated["is_multi_evidence"] = annotated["expected_documents_n"] >= 3

    metrics = [
        name
        for name in [
            "hit_at_1",
            "hit_at_3",
            "hit_at_5",
            "mrr",
            "ndcg_at_5",
            "citation_accuracy_at_k",
            "keyword_coverage_at_k",
            "safety_evidence_coverage",
        ]
        if name in annotated.columns
    ]
    frames = []
    for subset_name, subset_df in [
        ("full", annotated),
        ("multi_evidence", annotated[annotated["is_multi_evidence"]]),
    ]:
        if subset_df.empty:
            continue
        grouped = subset_df.groupby(["variant", "method"], as_index=False)[metrics].mean(numeric_only=True)
        grouped["subset"] = subset_name
        grouped["cases"] = len(subset_df[subset_df["variant"] == grouped.iloc[0]["variant"]]) if not grouped.empty else 0
        frames.append(grouped)
    summary = pd.concat(frames, ignore_index=True)
    summary["method"] = pd.Categorical(summary["method"], categories=METHOD_ORDER, ordered=True)
    return summary.sort_values(["subset", "method"]).reset_index(drop=True)


def load_chunks(database_url: str, max_chunks: int) -> pd.DataFrame | None:
    try:
        engine = create_engine(database_url, pool_pre_ping=True)
        query = text(
            """
            SELECT c.id::text AS id,
                   c.content,
                   c.metadata,
                   d.title,
                   d.filename,
                   c.embedding::text AS embedding
            FROM chunks c
            JOIN documents d ON d.id = c.document_id
            WHERE c.embedding IS NOT NULL
            ORDER BY d.title, c.created_at
            LIMIT :limit
            """
        )
        with engine.connect() as conn:
            rows = conn.execute(query, {"limit": max_chunks}).mappings().all()
    except Exception as exc:
        print(f"[skip] Failed to load chunks from database: {exc}", file=sys.stderr)
        return None

    records = []
    for row in rows:
        metadata = row["metadata"] or {}
        content = row["content"] or ""
        embedding = parse_vector(row["embedding"])
        if embedding is None:
            continue
        title = row["title"] or "unknown"
        system = infer_system(content, metadata, title)
        records.append(
            {
                "id": row["id"],
                "title": title,
                "filename": row["filename"],
                "system": system,
                "content_len": len(content),
                "domain_term_count": count_domain_terms(content, metadata),
                "dtc_count": count_dtc(content, metadata),
                "metadata_key_count": len(metadata) if isinstance(metadata, dict) else 0,
                "embedding_norm": float(np.linalg.norm(embedding)),
                "embedding": embedding,
            }
        )
    if not records:
        return pd.DataFrame()

    df = pd.DataFrame(records)
    embeddings = np.vstack(df["embedding"].to_numpy())
    pca = PCA(n_components=2, random_state=42)
    projection = pca.fit_transform(embeddings)
    df["pca_1"] = projection[:, 0]
    df["pca_2"] = projection[:, 1]
    df["pca_radius"] = np.sqrt(df["pca_1"] ** 2 + df["pca_2"] ** 2)
    df.attrs["explained_variance_ratio"] = pca.explained_variance_ratio_.tolist()
    return df


def parse_vector(raw: object) -> np.ndarray | None:
    if raw is None:
        return None
    if isinstance(raw, list):
        return np.array(raw, dtype=float)
    text_value = str(raw).strip()
    if text_value.startswith("[") and text_value.endswith("]"):
        text_value = text_value[1:-1]
    if not text_value:
        return None
    return np.fromstring(text_value, sep=",", dtype=float)


def infer_system(content: str, metadata: object, title: str) -> str:
    text_blob = f"{title}\n{content}\n{metadata}".lower()
    candidates = [
        ("快充/慢充", ["快充", "慢充", "obc", "充电"]),
        ("BMS/电池", ["bms", "电池", "soc", "绝缘"]),
        ("高压安全", ["高压", "hvil", "互锁", "绝缘"]),
        ("电驱/热管理", ["mcu", "电机", "水泵", "热管理", "限扭"]),
        ("通信/控制", ["can", "vcu", "离线", "报文"]),
    ]
    for label, terms in candidates:
        if any(term.lower() in text_blob for term in terms):
            return label
    return "其他"


def count_domain_terms(content: str, metadata: object) -> int:
    haystack = f"{content}\n{metadata}".lower()
    return sum(1 for term in DOMAIN_TERMS if term.lower() in haystack)


def count_dtc(content: str, metadata: object) -> int:
    import re

    haystack = f"{content}\n{metadata}".upper()
    return len(set(re.findall(r"\b[PCBU][0-9A-F]{4}\b", haystack)))


def save_current_figure(path: Path) -> Path:
    plt.tight_layout()
    plt.savefig(path, bbox_inches="tight")
    plt.close()
    return path


def plot_retrieval_ablation(summary: pd.DataFrame, figure_dir: Path) -> Path:
    focus_metrics = [name for name in ["hit_at_1", "mrr", "citation_accuracy_at_k", "keyword_coverage_at_k"] if name in summary.columns]
    fig, axes = plt.subplots(1, 2, figsize=(12.6, 4.8))

    full_df = summary[summary["subset"] == "full"].melt(
        id_vars=["method", "subset"], value_vars=focus_metrics, var_name="Metric", value_name="Score"
    )
    full_df["Metric"] = full_df["Metric"].map(METRIC_LABELS)
    sns.barplot(
        data=full_df,
        x="Metric",
        y="Score",
        hue="method",
        palette="Set2",
        edgecolor="0.25",
        ax=axes[0],
    )
    axes[0].set_ylim(0, 1.05)
    axes[0].set_xlabel("")
    axes[0].set_ylabel("Score")
    axes[0].set_title("Full Benchmark (64 queries)")

    subset_df = summary[(summary["subset"] == "multi_evidence") & (summary["method"] != "No RAG")].melt(
        id_vars=["method", "subset"], value_vars=focus_metrics, var_name="Metric", value_name="Score"
    )
    subset_df["Metric"] = subset_df["Metric"].map(METRIC_LABELS)
    sns.barplot(
        data=subset_df,
        x="Metric",
        y="Score",
        hue="method",
        palette="Set2",
        edgecolor="0.25",
        ax=axes[1],
    )
    axes[1].set_ylim(0.93, 1.005)
    axes[1].set_xlabel("")
    axes[1].set_ylabel("Score")
    axes[1].set_title("Multi-evidence Subset (28 harder queries)")

    handles, labels = axes[0].get_legend_handles_labels()
    axes[0].legend_.remove()
    axes[1].legend_.remove()
    fig.legend(handles, labels, title="Method", ncol=4, loc="upper center", bbox_to_anchor=(0.5, 1.05), frameon=True)
    fig.suptitle("Retrieval Ablation on NEV Diagnostic Queries", y=1.12)
    plt.subplots_adjust(top=0.82, wspace=0.16)
    return save_current_figure(figure_dir / "fig_retrieval_ablation.png")


def _csv_list_len(value: object) -> int:
    if value is None or (isinstance(value, float) and math.isnan(value)):
        return 0
    return len([item.strip() for item in str(value).split(",") if item.strip()])


def plot_retrieval_category_breakdown(df: pd.DataFrame, figure_dir: Path) -> Path:
    rename_map = {
        "dense": "Dense",
        "dense_only": "Dense",
        "dense_rerank": "Dense+Rerank",
        "dense_keyword": "Dense+Keyword",
        "hybrid_rerank": "Hybrid+Rerank",
        "no_rag": "No RAG",
    }
    plot_df = df.copy()
    plot_df["method"] = plot_df["variant"].map(rename_map).fillna(plot_df["variant"])
    plot_df = plot_df[plot_df["method"].isin(["Dense", "Hybrid+Rerank"])]
    category_order = ["dtc", "symptom", "cross_system", "safety", "case", "ocr"]
    metrics = ["hit_at_1", "citation_accuracy_at_k"]
    summary = (
        plot_df.groupby(["category", "method"], as_index=False)[metrics]
        .mean(numeric_only=True)
        .melt(id_vars=["category", "method"], value_vars=metrics, var_name="metric", value_name="score")
    )
    summary["metric"] = summary["metric"].map(METRIC_LABELS)
    summary["category"] = pd.Categorical(summary["category"], categories=category_order, ordered=True)

    fig, axes = plt.subplots(1, 2, figsize=(12.0, 4.4), sharey=True)
    for ax, metric_label in zip(axes, ["Hit@1", "Citation@K"]):
        metric_df = summary[summary["metric"] == metric_label]
        sns.barplot(
            data=metric_df,
            x="category",
            y="score",
            hue="method",
            palette=["#f4a261", "#5b8e7d"],
            edgecolor="0.25",
            ax=ax,
        )
        ax.set_title(metric_label)
        ax.set_xlabel("")
        ax.set_ylabel("Score" if ax is axes[0] else "")
        ax.set_ylim(0.9, 1.01)
        ax.tick_params(axis="x", rotation=25)
        if ax.legend_:
            ax.legend_.remove()

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=2, title="Method", frameon=True, bbox_to_anchor=(0.5, 1.06))
    fig.suptitle("Category-wise Retrieval Gains of Hybrid+Rerank", y=1.12)
    plt.subplots_adjust(top=0.8, wspace=0.08)
    return save_current_figure(figure_dir / "fig_retrieval_category_breakdown.png")


def plot_score_pairplot(df: pd.DataFrame, figure_dir: Path) -> Path:
    cols = [name for name in ["top_vector_score", "top_rerank_score", "top_score", "keyword_coverage_at_k", "latency_ms"] if name in df.columns]
    data = df[cols + ["category"]].copy()
    for col in cols:
        data[col] = pd.to_numeric(data[col], errors="coerce")
    data = data.dropna(subset=cols, how="all")
    if "latency_ms" in data:
        data["latency_s"] = data["latency_ms"] / 1000.0
        data = data.drop(columns=["latency_ms"])
    grid = sns.pairplot(
        data,
        hue="category" if "category" in data.columns else None,
        corner=True,
        diag_kind="hist",
        plot_kws={"s": 24, "alpha": 0.72, "linewidth": 0},
        diag_kws={"alpha": 0.82},
        palette="tab10",
        height=2.1,
    )
    grid.fig.suptitle("Retrieval Score and Latency Distribution", y=1.02)
    path = figure_dir / "fig_score_pairplot.png"
    grid.fig.savefig(path, bbox_inches="tight", dpi=300)
    plt.close(grid.fig)
    return path


def plot_latency_dashboard(df: pd.DataFrame, figure_dir: Path) -> Path:
    if "latency_ms" not in df.columns:
        return figure_dir / "fig_latency_dashboard_skipped.png"
    data = df.copy()
    data["latency_s"] = pd.to_numeric(data["latency_ms"], errors="coerce") / 1000.0
    data = data.dropna(subset=["latency_s"])
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2))
    sns.boxplot(data=data, x="category", y="latency_s", ax=axes[0], color="#8ecae6")
    sns.stripplot(data=data, x="category", y="latency_s", ax=axes[0], color="#023047", alpha=0.45, size=3)
    axes[0].set_title("Latency by Query Type")
    axes[0].set_xlabel("")
    axes[0].set_ylabel("Latency (s)")
    axes[0].tick_params(axis="x", rotation=25)
    if "top_rerank_score" in data.columns:
        data["top_rerank_score"] = pd.to_numeric(data["top_rerank_score"], errors="coerce")
        sns.scatterplot(data=data, x="top_rerank_score", y="latency_s", hue="category", ax=axes[1], s=38, alpha=0.75)
        axes[1].set_xlabel("Top rerank score")
    else:
        sns.histplot(data=data, x="latency_s", ax=axes[1], bins=18, color="#219ebc")
        axes[1].set_xlabel("Latency (s)")
    axes[1].set_title("Score-Latency Relationship")
    axes[1].set_ylabel("Latency (s)")
    return save_current_figure(figure_dir / "fig_latency_dashboard.png")


def plot_chunk_projection(df: pd.DataFrame, figure_dir: Path) -> Path:
    plt.figure(figsize=(8.2, 6.0))
    sns.scatterplot(data=df, x="pca_1", y="pca_2", hue="system", size="content_len", sizes=(28, 160), alpha=0.75)
    ratio = df.attrs.get("explained_variance_ratio", [math.nan, math.nan])
    plt.xlabel(f"PC1 ({ratio[0] * 100:.1f}% var.)" if not math.isnan(ratio[0]) else "PC1")
    plt.ylabel(f"PC2 ({ratio[1] * 100:.1f}% var.)" if not math.isnan(ratio[1]) else "PC2")
    plt.title("Knowledge Chunk Embedding Projection")
    plt.legend(title="Subsystem", frameon=True, bbox_to_anchor=(1.02, 1), loc="upper left")
    return save_current_figure(figure_dir / "fig_chunk_embedding_projection.png")


