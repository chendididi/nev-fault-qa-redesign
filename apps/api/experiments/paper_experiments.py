def plot_paper_dashboard(eval_df: pd.DataFrame, chunks_df: pd.DataFrame, figure_dir: Path) -> Path:
    fig, axes = plt.subplots(2, 2, figsize=(10, 8))
    doc_counts = chunks_df["title"].value_counts().head(8)
    sns.barplot(x=doc_counts.values, y=doc_counts.index, ax=axes[0, 0], palette="Set2", hue=doc_counts.index, legend=False)
    axes[0, 0].set_title("Chunk Count by Source Document")
    axes[0, 0].set_xlabel("Chunks")
    axes[0, 0].set_ylabel("")

    sns.scatterplot(data=chunks_df, x="pca_1", y="pca_2", hue="system", ax=axes[0, 1], s=36, alpha=0.68, legend=False)
    axes[0, 1].set_title("Embedding Space of Knowledge Chunks")
    axes[0, 1].set_xlabel("PC1")
    axes[0, 1].set_ylabel("PC2")

    plot_df = eval_df.copy()
    if "top_vector_score" in plot_df.columns and "top_rerank_score" in plot_df.columns:
        plot_df["top_vector_score"] = pd.to_numeric(plot_df["top_vector_score"], errors="coerce")
        plot_df["top_rerank_score"] = pd.to_numeric(plot_df["top_rerank_score"], errors="coerce")
        sns.scatterplot(data=plot_df, x="top_vector_score", y="top_rerank_score", hue="category", ax=axes[1, 0], s=34, alpha=0.72)
        axes[1, 0].set_xlabel("Vector score")
        axes[1, 0].set_ylabel("Rerank score")
    else:
        sns.histplot(data=plot_df, x="top_score", ax=axes[1, 0], bins=18)
        axes[1, 0].set_xlabel("Top score")
    axes[1, 0].set_title("Top Evidence Score Distribution")

    if "latency_ms" in plot_df.columns:
        plot_df["latency_s"] = pd.to_numeric(plot_df["latency_ms"], errors="coerce") / 1000.0
        sns.scatterplot(data=plot_df, x="keyword_coverage_at_k", y="latency_s", hue="category", ax=axes[1, 1], s=34, alpha=0.72)
        axes[1, 1].set_xlabel("Keyword coverage@k")
        axes[1, 1].set_ylabel("Latency (s)")
    else:
        sns.histplot(data=chunks_df, x="content_len", hue="system", ax=axes[1, 1], bins=20)
        axes[1, 1].set_xlabel("Chunk length")
    axes[1, 1].set_title("Coverage-Latency Relationship")

    handles, labels = axes[1, 0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, labels, loc="lower center", ncol=4, frameon=True)
        axes[1, 0].get_legend().remove()
    if axes[1, 1].get_legend():
        axes[1, 1].get_legend().remove()
    plt.subplots_adjust(bottom=0.12)
    return save_current_figure(figure_dir / "fig_experiment_dashboard.png")


